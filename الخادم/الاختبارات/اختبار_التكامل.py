"""
اختبار تكامل جميع الطبقات
"""

import pytest
import asyncio
from الطبقات.تحضير.محسن_الصور import تحسين_الصورة
from الطبقات.تقسيم.مقسم_الاجزاء import تقسيم_الاجزاء
from الطبقات.كشف.دمج_الكواشف import كشف_الاضرار
from الطبقات.تصنيف.مستوى_الضرر import تصنيف_مستوى_الضرر
from الطبقات.دمج.توحيد_النتائج import توحيد_النتائج
from الطبقات.دمج.تقدير_التكلفة import تقدير_التكلفة

@pytest.mark.asyncio
async def test_تكامل_جميع_الطبقات():
    """اختبار تكامل جميع طبقات الذكاء الاصطناعي"""
    
    # صورة اختبار
    with open('test_car.jpg', 'rb') as f:
        صورة = f.read()
    
    # الطبقة 1
    صورة_محسنة = await تحسين_الصورة(صورة)
    assert صورة_محسنة is not None
    
    # الطبقة 2
    الاجزاء = await تقسيم_الاجزاء([صورة_محسنة])
    assert len(الاجزاء) > 0
    
    # الطبقة 3
    الاضرار = await كشف_الاضرار([صورة_محسنة])
    assert len(الاضرار) > 0
    
    # الطبقة 4
    for ضرر in الاضرار:
        ضرر['مستوى_الضرر'] = await تصنيف_مستوى_الضرر(ضرر)
        assert ضرر['مستوى_الضرر'] in ['خفيف', 'متوسط', 'جسيم', 'غير محدد']
    
    # الطبقة 5
    النهائية = await توحيد_النتائج(الاضرار)
    assert len(النهائية) > 0
    
    التكلفة = await تقدير_التكلفة(النهائية, الاجزاء)
    assert 'التكلفة_الاجمالية' in التكلفة

@pytest.mark.asyncio
async def test_سرعة_التحليل():
    """اختبار سرعة التحليل (يجب أن يكون أقل من 5 ثواني)"""
    import time
    
    with open('test_car.jpg', 'rb') as f:
        صورة = f.read()
    
    البداية = time.time()
    
    صورة_محسنة = await تحسين_الصورة(صورة)
    الاضرار = await كشف_الاضرار([صورة_محسنة])
    النهائية = await توحيد_النتائج(الاضرار)
    
    المدة = time.time() - البداية
    
    assert المدة < 5.0, f"التحليل استغرق {المدة:.2f} ثانية"
