"""
نظام مراقبة أداء النماذج
"""

import time
import json
from datetime import datetime
from typing import Dict, List

class مراقب_الأداء:
    def __init__(self):
        self.سجل_الأداء = []
        self.عتبة_الدقة = 0.85
        self.عتبة_السرعة = 5.0  # ثواني
    
    def سجل_تحليل(self, معرف: str, وقت_البدء: float, نتائج: Dict):
        """تسجيل أداء تحليل واحد"""
        
        المدة = time.time() - وقت_البدء
        عدد_الأضرار = len(نتائج.get('الأضرار', []))
        الثقة = نتائج.get('الثقة_الكلية', 0)
        
        سجل = {
            'المعرف': معرف,
            'الوقت': datetime.now().isoformat(),
            'المدة': round(المدة, 3),
            'عدد_الأضرار': عدد_الأضرار,
            'الثقة': الثقة,
            'حالة_السرعة': 'جيد' if المدة < self.عتبة_السرعة else 'بطيء',
            'حالة_الدقة': 'جيد' if الثقة > self.عتبة_الدقة else 'منخفض'
        }
        
        self.سجل_الأداء.append(سجل)
        
        # تنبيه إذا كان هناك مشكلة
        if المدة > self.عتبة_السرعة:
            self._تنبيه(f"⚠️ تحليل بطيء: {المدة:.1f} ثانية")
        
        if الثقة < self.عتبة_الدقة:
            self._تنبيه(f"⚠️ دقة منخفضة: {الثقة:.2f}")
    
    def تقرير_يومي(self) -> Dict:
        """تقرير إحصائي يومي"""
        
        if not self.سجل_الأداء:
            return {'الحالة': 'لا_توجد_بيانات'}
        
        تحليلات_اليوم = [س for س in self.سجل_الأداء 
                        if س['الوقت'][:10] == datetime.now().strftime('%Y-%m-%d')]
        
        if not تحليلات_اليوم:
            return {'الحالة': 'لا_توجد_تحليلات_اليوم'}
        
        return {
            'عدد_التحليلات': len(تحليلات_اليوم),
            'متوسط_المدة': round(sum(ت['المدة'] for ت in تحليلات_اليوم) / len(تحليلات_اليوم), 3),
            'متوسط_الثقة': round(sum(ت['الثقة'] for ت in تحليلات_اليوم) / len(تحليلات_اليوم), 3),
            'متوسط_الأضرار': round(sum(ت['عدد_الأضرار'] for ت in تحليلات_اليوم) / len(تحليلات_اليوم), 1),
            'نسبة_البطء': sum(1 for ت in تحليلات_اليوم if ت['حالة_السرعة'] == 'بطيء') / len(تحليلات_اليوم),
            'نسبة_الدقة_المنخفضة': sum(1 for ت in تحليلات_اليوم if ت['حالة_الدقة'] == 'منخفض') / len(تحليلات_اليوم)
        }
    
    def _تنبيه(self, رسالة: str):
        """إرسال تنبيه"""
        print(f"🚨 {رسالة}")
        # يمكن إضافة إرسال إشعار للمطورين
