"""
جدولة التدريب التلقائي
"""

import asyncio
from datetime import datetime
from .مدير_التدريب import مدير_التدريب
from .مجمع_البيانات import مجمع_البيانات
from .مدير_الإصدارات import مدير_الإصدارات
import os

class جدولة_التدريب:
    def __init__(self):
        self.مدير_التدريب = مدير_التدريب()
        self.مجمع = مجمع_البيانات()
        self.مدير_الإصدارات = مدير_الإصدارات()
        
        self.الحد_الأدنى_للصور = 100  # أقل عدد صور لبدء التدريب
        self.جدول_التدريب = 'أسبوعي'  # يومي، أسبوعي، شهري
    
    async def تشغيل_الجدولة(self):
        """تشغيل الجدولة في الخلفية"""
        
        while True:
            الآن = datetime.now()
            
            # تدريب أسبوعي كل يوم اثنين الساعة 3 صباحاً
            if الآن.weekday() == 0 and الآن.hour == 3:
                await self._تنفيذ_التدريب_المجدول()
            
            await asyncio.sleep(3600)  # فحص كل ساعة
    
    async def _تنفيذ_التدريب_المجدول(self):
        """تنفيذ دورة تدريب مجدولة"""
        
        print("📅 بدء التدريب المجدول...")
        
        # جمع المساهمات المعتمدة
        مساهمات = os.listdir("بيانات/معتمدة")
        عدد_الصور = sum(len(os.listdir(f"بيانات/معتمدة/{م}/images"))
                       for م in مساهمات if os.path.exists(f"بيانات/معتمدة/{م}/images"))
        
        if عدد_الصور < self.الحد_الأدنى_للصور:
            print(f"❌ عدد الصور غير كاف: {عدد_الصور} (الحد الأدنى: {self.الحد_الأدنى_للصور})")
            return
        
        # تحضير البيانات
        مسار_التدريب = await self.مدير_التدريب.تحضير_البيانات("بيانات/معتمدة", [])
        
        # تدريب
        نتائج = await self.مدير_التدريب.تدريب(مسار_التدريب)
        
        # تقييم
        مقاييس = await self.مدير_التدريب.تقييم_النموذج(
            f"{نتائج.save_dir}/weights/best.pt",
            "بيانات/اختبار"
        )
        
        # مقارنة مع الإصدار الحالي
        if مقاييس['الدقة'] > 0.85:  # عتبة النشر
            إصدار = self.مدير_الإصدارات.حفظ_إصدار(
                f"{نتائج.save_dir}/weights/best.pt",
                مقاييس
            )
            
            # نشر تدريجي
            self.مدير_الإصدارات.نشر_إصدار(إصدار, نسبة_الحركة=0.1)
            
            print(f"✅ تم نشر الإصدار {إصدار} بنسبة 10%")
        else:
            print(f"❌ الدقة غير كافية للنشر: {مقاييس['الدقة']:.3f}")
